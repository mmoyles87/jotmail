#!/usr/bin/env python3
"""Write src/tables.inc: the HTML5 named character references and the Unicode
classes behind Python's \\s, \\w and \\d, so the C++ text handling matches Python's.

    python3 tools/gen-tables.py > src/tables.inc
"""
import html.entities
import re
import sys
import unicodedata


def ranges(pattern):
    rx = re.compile(pattern)
    out, start = [], None
    for c in range(0x110000):
        hit = 0xD800 <= c <= 0xDFFF and False or bool(rx.match(chr(c)))
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def c_bytes(s):
    return '"' + "".join(f"\\x{b:02X}" for b in s.encode("utf-8")) + '"'


w = sys.stdout.write
w(f"// Generated by tools/gen-tables.py (Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}).\n")
w("// Do not edit by hand.\n\n")

w("struct NamedRef { const char* name; const char* utf8; };\n")
w("static const NamedRef NAMED_REFS[] = {\n")
for name in sorted(html.entities.html5, key=lambda n: n.encode()):
    w(f'    {{"{name}", {c_bytes(html.entities.html5[name])}}},\n')
w("};\n\n")

for ident, pattern in (("SPACE", r"\s"), ("WORD", r"\w"), ("DIGIT", r"\d")):
    rs = ranges(pattern)
    w(f"static const char32_t {ident}_RANGES[][2] = {{\n")
    for a, b in rs:
        w(f"    {{0x{a:X}, 0x{b:X}}},\n")
    w("};\n\n")
